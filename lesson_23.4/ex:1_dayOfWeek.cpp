#include <iostream>

// ============================================================================
// МАКРОСЫ ДЛЯ ЧИСЛОВЫХ ЗНАЧЕНИЙ ДНЕЙ НЕДЕЛИ
// ============================================================================

#define SUNDAY 1// Везде, где встретится SUNDAY, препроцессор подставит 1
#define MONDAY 2// Аналогично: MONDAY -> 2
#define TUESDAY 3// TUESDAY -> 3
#define WEDNESDAY 4// WEDNESDAY -> 4
#define THURSDAY 5// THURSDAY -> 5
#define FRIDAY 6// FRIDAY -> 6
#define SATURDAY 7// SATURDAY -> 7

// ============================================================================
// МАКРОСЫ ДЛЯ СТРОКОВЫХ ЛИТЕРАЛОВ (НАЗВАНИЙ ДНЕЙ)
// ============================================================================

#define SUNDAY_NAME "Sunday"// SUNDAY_NAME -> "Sunday"
#define MONDAY_NAME "Monday"// MONDAY_NAME -> "Monday"
#define TUESDAY_NAME "Tuesday"// TUESDAY_NAME -> "Tuesday"
#define WEDNESDAY_NAME "Wednesday"// WEDNESDAY_NAME -> "Wednesday"
#define THURSDAY_NAME "Thursday"// THURSDAY_NAME -> "Thursday"
#define FRIDAY_NAME "Friday"// FRIDAY_NAME -> "Friday"
#define SATURDAY_NAME "Saturday"// SATURDAY_NAME -> "Saturday"

// ============================================================================
// МАКРОС С КОНКАТЕНАЦИЕЙ ТОКЕНОВ (САМЫЙ ВАЖНЫЙ МОМЕНТ)
// ============================================================================

// Оператор ## (двойной решётка) - это оператор конкатенации (склеивания) токенов
// Он работает ТОЛЬКО в макросах и склеивает левую и правую части в один токен

// Макрос GET_NAME принимает один параметр - index
// index##_NAME означает: взять то, что передано в index, и склеить с "_NAME"
#define GET_NAME(index) index##_NAME

// КАК ЭТО РАБОТАЕТ (ВАЖНО!):
//
// Когда мы пишем: GET_NAME(SUNDAY)
//
// Шаг 1: Препроцессор видит вызов макроса GET_NAME с аргументом SUNDAY
// Шаг 2: Подставляет SUNDAY вместо index в тело макроса: SUNDAY##_NAME
// Шаг 3: Оператор ## склеивает SUNDAY и _NAME в один токен: SUNDAY_NAME
// Шаг 4: Препроцессор проверяет, определён ли макрос SUNDAY_NAME
// Шаг 5: SUNDAY_NAME определён как "Sunday", поэтому подставляет "Sunday"
//
// Таким образом, GET_NAME(SUNDAY) превращается в "Sunday"!

// ПОЧЕМУ ЭТО РАБОТАЕТ ТОЛЬКО С МАКРОСАМИ?
// - Оператор ## существует только на этапе препроцессинга
// - В обычном коде C++ такого оператора нет
// - Это позволяет динамически формировать имена других макросов

int main()
{
    // Единственная обычная переменная в программе - для хранения ввода пользователя
    // По заданию разрешено использовать переменные ТОЛЬКО для хранения ввода
    int day;

    // Ввод номера дня с консоли
    std::cin >> day;

    // ========================================================================
    // ЦЕПОЧКА ПРОВЕРОК if-else
    // ========================================================================

    if (day == SUNDAY)// После препроцессинга: if (day == 1)
    {
        // GET_NAME(SUNDAY) раскрывается так:
        // 1. SUNDAY##_NAME -> SUNDAY_NAME
        // 2. SUNDAY_NAME -> "Sunday"
        // 3. В итоге: std::cout << "Sunday" << std::endl;
        std::cout << GET_NAME(SUNDAY) << std::endl;
    }
    else if (day == MONDAY)// else if (day == 2)
    {
        // GET_NAME(MONDAY) -> MONDAY##_NAME -> MONDAY_NAME -> "Monday"
        std::cout << GET_NAME(MONDAY) << std::endl;
    }
    else if (day == TUESDAY)// else if (day == 3)
    {
        // GET_NAME(TUESDAY) -> TUESDAY##_NAME -> TUESDAY_NAME -> "Tuesday"
        std::cout << GET_NAME(TUESDAY) << std::endl;
    }
    else if (day == WEDNESDAY)// else if (day == 4)
    {
        // GET_NAME(WEDNESDAY) -> WEDNESDAY##_NAME -> WEDNESDAY_NAME -> "Wednesday"
        std::cout << GET_NAME(WEDNESDAY) << std::endl;
    }
    else if (day == THURSDAY)// else if (day == 5)
    {
        // GET_NAME(THURSDAY) -> THURSDAY##_NAME -> THURSDAY_NAME -> "Thursday"
        std::cout << GET_NAME(THURSDAY) << std::endl;
    }
    else if (day == FRIDAY)// else if (day == 6)
    {
        // GET_NAME(FRIDAY) -> FRIDAY##_NAME -> FRIDAY_NAME -> "Friday"
        std::cout << GET_NAME(FRIDAY) << std::endl;
    }
    else if (day == SATURDAY)// else if (day == 7)
    {
        // GET_NAME(SATURDAY) -> SATURDAY##_NAME -> SATURDAY_NAME -> "Saturday"
        std::cout << GET_NAME(SATURDAY) << std::endl;
    }
}

// ============================================================================
// ПРИМЕР РАБОТЫ ПРЕПРОЦЕССОРА (КАК ВЫГЛЯДИТ КОД ПОСЛЕ МАКРОСОВ)
// ============================================================================

/*
Допустим, пользователь ввёл число 3.

Исходный код (фрагмент):
    if (day == TUESDAY)
    {
        std::cout << GET_NAME(TUESDAY) << std::endl;
    }

Первый проход препроцессора (замена TUESDAY на 3):
    if (day == 3)
    {
        std::cout << GET_NAME(3) << std::endl;  // Ошибка! GET_NAME(3) не определён
    }

НО! ВАЖНО: На самом деле препроцессор работает иначе:
    Он НЕ ПОДСТАВЛЯЕТ 3 вместо TUESDAY ДО вызова GET_NAME.

Правильная последовательность:
    1. Препроцессор видит GET_NAME(TUESDAY)
    2. TUESDAY внутри GET_NAME НЕ ЗАМЕНЯЕТСЯ на 3 (потому что это аргумент макроса)
    3. Происходит склейка: TUESDAY##_NAME = TUESDAY_NAME
    4. TUESDAY_NAME заменяется на "Tuesday"
    5. Только потом внешний TUESDAY в условии if заменяется на 3

Поэтому конечный код после препроцессинга выглядит так:

    if (day == 3)
    {
        std::cout << "Tuesday" << std::endl;
    }
*/

// ============================================================================
// ПРЕИМУЩЕСТВА И НЕДОСТАТКИ МАКРОСОВ
// ============================================================================

/*
ПРЕИМУЩЕСТВА:
1. Скорость - нет вызовов функций, всё решается на этапе компиляции
2. Гибкость - можно создавать динамические имена (через ##)
3. Экономия памяти - макросы не создают переменных
4. Кроссплатформенность - работают во всех компиляторах C/C++

НЕДОСТАТКИ:
1. Нет проверки типов - макросы работают просто с текстом
2. Сложность отладки - в отладчике виден уже раскрытый код
3. Проблемы с областями видимости - макросы глобальны
4. Могут приводить к неочевидным ошибкам
5. Нельзя взять адрес макроса (это не переменная)
*/

